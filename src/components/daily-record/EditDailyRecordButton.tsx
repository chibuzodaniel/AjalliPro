"use client";

import { useState } from "react";
import DailyRecordFormModal, { type DailyRecordFormInitial } from "./DailyRecordFormModal";
import { isAutoGeneratedExpense, type DailyRecordFull } from "@/lib/records";

interface DriverOption {
  id: string;
  name: string;
  pricePerBag: number;
  loadingFee: number;
}
interface CustomerOption {
  id: string;
  name: string;
  pricePerBag: number;
}
interface BankAccountOption {
  id: string;
  bankName: string;
  accountName: string;
  accountNumber: string;
}
interface PackerOption {
  id: string;
  name: string;
}
interface PackingBagTypeOption {
  id: string;
  name: string;
  pricePerBundle: number;
}
export default function EditDailyRecordButton({
  record,
  drivers,
  customers,
  bankAccounts,
  packers,
  canEditOpeningStock,
  canEditFactoryPrice,
  canEditLeakageOpening,
  packerPricePerBag,
  truckLoadingFeePerBag,
  truckOffloadingFeePerBag,
  truckHiredCostPerBag,
  rollsPricePerKg,
  packingBagTypes,
}: {
  record: DailyRecordFull;
  drivers: DriverOption[];
  customers: CustomerOption[];
  bankAccounts: BankAccountOption[];
  packers: PackerOption[];
  canEditOpeningStock?: boolean;
  canEditFactoryPrice?: boolean;
  canEditLeakageOpening?: boolean;
  packerPricePerBag: number;
  truckLoadingFeePerBag: number;
  truckOffloadingFeePerBag: number;
  truckHiredCostPerBag: number;
  rollsPricePerKg: number;
  packingBagTypes: PackingBagTypeOption[];
}) {
  const [open, setOpen] = useState(false);

  const initial: DailyRecordFormInitial = {
    date: record.date,
    openingStock: record.openingStock,
    production: record.productionLines.map((p) => ({
      packerName: p.packer.name,
      bags: p.bags,
    })),
    factoryBags: record.factoryBags,
    factoryBagsFromLeakage: record.factoryBagsFromLeakage,
    factoryPricePerBag: record.factoryPricePerBag,
    factoryCustomerId: record.factoryCustomerId,
    pumpWaterAmount: record.pumpWaterAmount,
    driverSales: record.driverSales.map((d) => ({
      driverId: d.driverId,
      bags: d.bags,
      bonusBags: d.bonusBags,
      loadingFeeWaived: d.loadingFeeWaived,
      bagsFromLeakage: d.bagsFromLeakage,
    })),
    truckDeliveries: record.truckDeliveries.map((t) => ({
      customerId: t.customerId,
      bags: t.bags,
      bonusBags: t.bonusBags,
      ownTruck: t.ownTruck,
      fuelCost: t.fuelCost,
      loadingFeeWaived: t.loadingFeeWaived,
      offloadingFeeWaived: t.offloadingFeeWaived,
      hiredCostWaived: t.hiredCostWaived,
      bagsFromLeakage: t.bagsFromLeakage,
    })),
    leakageBags: record.leakageBags,
    leakageWasteBags: record.leakageWasteBags,
    expenses: record.expenseItems
      .filter((e) => !isAutoGeneratedExpense(e.description))
      .map((e) => ({ description: e.description, amount: e.amount, paid: e.paid })),
    bankAccountId: record.bankAccountId,
    bankAmountSent: record.bankAmountSent,
  };

  return (
    <>
      <button className="icon-btn no-print" title="Edit this record" onClick={() => setOpen(true)}>
        ✎
      </button>
      {open && (
        <DailyRecordFormModal
          mode="edit"
          recordId={record.id}
          open={open}
          onClose={() => setOpen(false)}
          initial={initial}
          leakageOpening={record.leakageOpening}
          drivers={drivers}
          customers={customers}
          bankAccounts={bankAccounts}
          packers={packers}
          canEditOpeningStock={canEditOpeningStock}
          canEditFactoryPrice={canEditFactoryPrice}
          canEditLeakageOpening={canEditLeakageOpening}
          packerPricePerBag={packerPricePerBag}
          truckLoadingFeePerBag={truckLoadingFeePerBag}
          truckOffloadingFeePerBag={truckOffloadingFeePerBag}
          truckHiredCostPerBag={truckHiredCostPerBag}
          rollsPricePerKg={rollsPricePerKg}
          packingBagTypes={packingBagTypes}
        />
      )}
    </>
  );
}
