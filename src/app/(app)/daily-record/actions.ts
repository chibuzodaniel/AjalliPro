/**
 * Quick-add from the Total Produced page. If the date has no record yet,
 * creates a minimal one (production only, everything else defaulted) via
 * the normal create path. If a record already exists, appends to its
 * production and re-saves via the normal update path — reusing both so
 * stock recalculation, approval status, and permission checks all stay
 * exactly as correct as they are for the full form.
 */
export async function addProductionForDate(
  date: string,
  newProduction: { packerName: string; bags: number }[]
): Promise<AddProductionResult> {
  await requireUser();
  if (!/^\d{4}-\d{2}-\d{2}$/.test(date)) {
    return { ok: false, error: "Invalid date" };
  }
  const cleaned = newProduction
    .map((p) => ({ packerName: p.packerName.trim(), bags: p.bags }))
    .filter((p) => p.packerName && p.bags > 0);
  if (cleaned.length === 0) {
    return { ok: false, error: "Add at least one packer with bags." };
  }

  const existing = await prisma.dailyRecord.findUnique({ where: { date }, include: dailyRecordInclude });

  if (!existing) {
    return createDailyRecord({
      date,
      openingStockOverride: null,
      leakageOpeningOverride: null,
      production: cleaned,
      factoryBags: 0,
      factoryBagsFromLeakage: 0,
      factoryPricePerBag: 0,
      factoryCustomerId: null,
      pumpWaterAmount: 0,
      driverSales: [],
      truckDeliveries: [],
      leakageBags: 0,
      leakageWasteBags: 0,
      expenses: [],
    });
  }

  const combinedProduction = [
    ...existing.productionLines.map((p) => ({
      packerName: p.packer.name,
      bags: p.bags,
    })),
    ...cleaned,
  ];
  return updateDailyRecord(existing.id, {
    date: existing.date,
    openingStockOverride: null,
    leakageOpeningOverride: null,
    production: combinedProduction,
    factoryBags: existing.factoryBags,
    factoryBagsFromLeakage: existing.factoryBagsFromLeakage,
    factoryPricePerBag: existing.factoryPricePerBag,
    factoryCustomerId: existing.factoryCustomerId,
    pumpWaterAmount: existing.pumpWaterAmount,
    driverSales: existing.driverSales.map((d) => ({
      driverId: d.driverId,
      bags: d.bags,
      bonusBags: d.bonusBags,
      loadingFeeWaived: d.loadingFeeWaived,
      bagsFromLeakage: d.bagsFromLeakage,
    })),
    truckDeliveries: existing.truckDeliveries.map((t) => ({
      customerId: t.customerId,
      bags: t.bags,
      bonusBags: t.bonusBags,
      ownTruck: t.ownTruck,
      fuelCost: t.fuelCost,
      loadingFeeWaived: t.loadingFeeWaived,
      offloadingFeeWaived: t.offloadingFeeWaived,
      hiredCostWaived: t.hiredCostWaived,
      bagsFromLeakage: t.bagsFromLeakage,
    })),
    leakageBags: existing.leakageBags,
    leakageWasteBags: existing.leakageWasteBags,
    expenses: existing.expenseItems
      .filter((e) => !isAutoGeneratedExpense(e.description))
      .map((e) => ({ description: e.description, amount: e.amount, paid: e.paid })),
    bankAccountId: existing.bankAccountId,
    bankAmountSent: existing.bankAmountSent,
  });
}

export interface ConfirmBankMoneyReceivedResult {
  ok: boolean;
  error?: string;
}

/**
 * Admin/Super Admin confirms the amount logged against a bank account
 * actually landed — only confirmed amounts count toward that account's
 * balance (see getBankAccountsWithBalances). Can also be un-confirmed if
 * ticked by mistake.
 */
export async function confirmBankMoneyReceived(recordId: string, received: boolean): Promise<ConfirmBankMoneyReceivedResult> {
  const guard = await requireRoleSafe(["ADMIN", "SUPER_ADMIN"]);
  if (!guard.ok) return { ok: false, error: guard.error };
  const user = guard.user;

  const record = await prisma.dailyRecord.findUnique({ where: { id: recordId }, include: { bankAccount: true } });
  if (!record) return { ok: false, error: "Record not found." };
  if (!record.bankAccountId) return { ok: false, error: "This record has no bank account selected." };

  await prisma.dailyRecord.update({
    where: { id: recordId },
    data: received
      ? { bankMoneyReceived: true, bankReceivedAt: new Date(), bankReceivedById: user.id }
      : { bankMoneyReceived: false, bankReceivedAt: null, bankReceivedById: null },
  });
  await logActivity(
    received
      ? `${user.name} confirmed ${formatMoney(record.bankAmountSent)} received into "${record.bankAccount?.bankName}" for ${record.date}.`
      : `${user.name} un-confirmed the bank transfer for ${record.date}.`,
    user.id
  );
  revalidatePath("/", "layout");
  return { ok: true };
}
