async function cascadeRecalculate(
  tx: Prisma.TransactionClient,
  fromDate: string,
  startingClosingStock: number,
  startingLeakageClosing: number,
  excludeId?: string
) {
  // Pending records are re-synced too (their opening follows the approved
  // chain), but only approved records carry their closing forward — a
  // pending one may still be rejected.
  const forward = await tx.dailyRecord.findMany({
    where: { status: { in: ["APPROVED", "PENDING"] }, archivedAt: null, date: { gt: fromDate } },
    include: dailyRecordInclude,
    orderBy: { date: "asc" },
  });

  let runningClosing = startingClosingStock;
  let runningLeakageClosing = startingLeakageClosing;

  for (const rec of forward) {
    if (rec.id === excludeId) {
      if (rec.status !== "APPROVED") continue;
      // Its opening/closing were already set explicitly (e.g. a Super Admin override) —
      // don't recompute it, just carry its already-saved closing forward.
      runningClosing = rec.closingStock;
      runningLeakageClosing = rec.leakageClosing;
      continue;
    }
    const opening = runningClosing;
    const leakageOpening = runningLeakageClosing;

    const driverTruckBagsFromLeakageTotal = recordDriverTruckBagsFromLeakageTotal(rec);
    const closing = computeClosingStock({
      opening,
      prodTotal: recordProdTotal(rec),
      factoryBags: rec.factoryBags,
      factoryBagsFromLeakage: rec.factoryBagsFromLeakage,
      driverBagsTotal: recordDriverBagsTotal(rec),
      driverBonusBagsTotal: recordDriverBonusBagsTotal(rec),
      truckDeliveryBagsTotal: recordTruckDeliveryBagsTotal(rec),
      truckDeliveryBonusBagsTotal: recordTruckDeliveryBonusBagsTotal(rec),
      driverTruckBagsFromLeakage: driverTruckBagsFromLeakageTotal,
      leakageBagsNew: rec.leakageBags,
      incentiveBonusBags: rec.incentiveBonusBags,
    });
    const leakageClosing = computeLeakageClosing(
      leakageOpening,
      rec.leakageBags,
      rec.factoryBagsFromLeakage,
      driverTruckBagsFromLeakageTotal,
      rec.leakageWasteBags,
      rec.incentiveBonusBagsFromLeakage
    );

    await tx.dailyRecord.update({
      where: { id: rec.id },
      data: { openingStock: opening, closingStock: closing, leakageOpening, leakageClosing },
    });

    if (rec.status !== "APPROVED") continue;
    runningClosing = closing;
    runningLeakageClosing = leakageClosing;
  }
}

/**
 * `fromNewEntry`: the save comes from "New daily entry" continuing a record
 * that already exists for that date — only allowed while the record is
 * production-only (Total Produced quick-add); anything fuller must go
 * through that record's Edit button.
 */
export async function updateDailyRecord(
  id: string,
  input: unknown,
  opts: { fromNewEntry?: boolean } = {}
): Promise<UpdateDailyRecordResult> {
  const user = await requireUser();
  const parsed = dailyRecordEditSchema.safeParse(input);
  if (!parsed.success) {
    return { ok: false, error: parsed.error.issues[0]?.message ?? "Invalid input" };
  }
  const data = parsed.data;

  const existing = await prisma.dailyRecord.findUnique({
    where: { id },
    include: { driverSales: { select: { id: true } }, truckDeliveries: { select: { id: true } }, expenseItems: { select: { id: true } } },
  });
  if (!existing) {
    return { ok: false, error: "Daily record not found." };
  }
  if (existing.archivedAt) {
    return { ok: false, error: "This record is archived and read-only." };
  }
  if (opts.fromNewEntry && !isProductionOnly(existing)) {
    return {
      ok: false,
      error: `${formatDay(existing.date)} has already been filled. Use the Edit button on that day's record to change it.`,
    };
  }

  const canEdit = isApprover(user.role) || (existing.createdById === user.id && existing.status === "PENDING");
  if (!canEdit) {
    return { ok: false, error: "You don't have permission to edit this record." };
  }
  try {
    await requireEditingEnabled(user.id);
  } catch (err) {
    return { ok: false, error: err instanceof Error ? err.message : "You don't have permission to do that." };
  }

  const dateChanged = data.date !== existing.date;
  if (dateChanged) {
    const conflict = await prisma.dailyRecord.findUnique({ where: { date: data.date } });
    if (conflict && conflict.id !== id) {
      return { ok: false, error: `A daily record for ${data.date} already exists.` };
    }
    const unfilled = await findUnfilledDates(data.date, { excludeId: id, oldDate: existing.date });
    if (hasUnfilled(unfilled)) {
      return { ok: false, error: unfilledDatesMessage(unfilled, isAdminRole(user.role)), unfilled };
    }
  }

  const [fixedPricing, packingBagTypes, drivers, truckCustomers, packerByName, prevApprovedForNewDate] = await Promise.all([
    getPricingSettings(),
    getPackingBagTypes(),
    prisma.driver.findMany({ where: { id: { in: data.driverSales.map((d) => d.driverId) } } }),
    prisma.customer.findMany({
      where: { id: { in: data.truckDeliveries.map((t) => t.customerId) } },
    }),
    resolvePackers(
      data.production.map((p) => p.packerName),
      user.id
    ),
    dateChanged
      ? prisma.dailyRecord.findFirst({
          where: { status: "APPROVED", archivedAt: null, date: { lt: data.date }, id: { not: id } },
          orderBy: { date: "desc" },
        })
      : Promise.resolve(null),
  ]);

  const overrideApplied =
    user.role === "SUPER_ADMIN" &&
    (data.openingStockOverride != null ||
      data.leakageOpeningOverride != null ||
      data.closingStockOverride != null ||
      data.leakageClosingOverride != null);
  const opening =
    user.role === "SUPER_ADMIN" && data.openingStockOverride != null
      ? data.openingStockOverride
      : dateChanged
        ? (prevApprovedForNewDate?.closingStock ?? 0)
        : existing.openingStock;
  const leakageOpening =
    user.role === "SUPER_ADMIN" && data.leakageOpeningOverride != null
      ? data.leakageOpeningOverride
      : dateChanged
        ? (prevApprovedForNewDate?.leakageClosing ?? 0)
        : existing.leakageOpening;

  const rowError = validateBagsFromLeakagePerRow(data.driverSales, data.truckDeliveries);
  if (rowError) return { ok: false, error: rowError };

  const driverTruckBagsFromLeakageTotal =
    data.driverSales.reduce((s, d) => s + d.bagsFromLeakage, 0) +
    data.truckDeliveries.reduce((s, t) => s + t.bagsFromLeakage, 0);

  // Today's new leakage can be rebagged (and sold or wasted) the same day, so it counts as available.
  // Bags already taken from this day's leakage pile for approved weekly bonuses still count against it.
  const leakageAvailable = leakageOpening + data.leakageBags;
  if (
    data.factoryBagsFromLeakage +
      driverTruckBagsFromLeakageTotal +
      data.leakageWasteBags +
      existing.incentiveBonusBagsFromLeakage >
    leakageAvailable
  ) {
    return {
      ok: false,
      error: `Only ${leakageAvailable} bags are available in the leakage pile to sell, rebag, or waste (${leakageOpening} carried over + ${data.leakageBags} new today)${existing.incentiveBonusBagsFromLeakage > 0 ? ` — ${existing.incentiveBonusBagsFromLeakage} already went to approved weekly bonuses` : ""}.`,
    };
  }

  const prodTotal = data.production.reduce((s, p) => s + p.bags, 0);
  const driverBagsTotal = data.driverSales.reduce((s, d) => s + d.bags, 0);
  const driverBonusBagsTotal = data.driverSales.reduce((s, d) => s + d.bonusBags, 0);
  const truckDeliveryBagsTotal = data.truckDeliveries.reduce((s, t) => s + t.bags, 0);
  const truckDeliveryBonusBagsTotal = data.truckDeliveries.reduce((s, t) => s + t.bonusBags, 0);

  const computedClosing = computeClosingStock({
    opening,
    prodTotal,
    factoryBags: data.factoryBags,
    factoryBagsFromLeakage: data.factoryBagsFromLeakage,
    driverBagsTotal,
    driverBonusBagsTotal,
    truckDeliveryBagsTotal,
    truckDeliveryBonusBagsTotal,
    driverTruckBagsFromLeakage: driverTruckBagsFromLeakageTotal,
    leakageBagsNew: data.leakageBags,
    incentiveBonusBags: existing.incentiveBonusBags,
  });
  const computedLeakageClosing = computeLeakageClosing(
    leakageOpening,
    data.leakageBags,
    data.factoryBagsFromLeakage,
    driverTruckBagsFromLeakageTotal,
    data.leakageWasteBags,
    existing.incentiveBonusBagsFromLeakage
  );
  const closing =
    user.role === "SUPER_ADMIN" && data.closingStockOverride != null ? data.closingStockOverride : computedClosing;
  const leakageClosing =
    user.role === "SUPER_ADMIN" && data.leakageClosingOverride != null
      ? data.leakageClosingOverride
      : computedLeakageClosing;

  const canEditFactoryPrice = user.role === "ADMIN" || user.role === "SUPER_ADMIN";
  const factoryPricePerBag = canEditFactoryPrice ? data.factoryPricePerBag : fixedPricing.factoryPricePerBag;
  const driverById = new Map(drivers.map((d) => [d.id, d]));
  const truckCustomerById = new Map(truckCustomers.map((c) => [c.id, c]));

  const newBankAccountId = data.bankAccountId || null;
  const newBankAmountSent = newBankAccountId ? data.bankAmountSent : 0;
  // Changing which account the money went to, or how much, invalidates any
  // existing Admin/Super Admin confirmation that it landed — it needs to be
  // re-confirmed against the new figures.
  const bankDetailsChanged =
    newBankAccountId !== existing.bankAccountId || newBankAmountSent !== existing.bankAmountSent;

  const desiredExpenses: DesiredExpense[] = [
    ...data.expenses.map((e) => {
      const matchedType = matchPackingBagType(e.description, packingBagTypes);
      return {
        description: e.description,
        amount: e.amount,
        paid: e.paid,
        rollsKg:
          isRollsExpense(e.description) && fixedPricing.rollsPricePerKg > 0 ? e.amount / fixedPricing.rollsPricePerKg : null,
        packingBagsBundles: matchedType && matchedType.pricePerBundle > 0 ? e.amount / matchedType.pricePerBundle : null,
        packingBagTypeId: matchedType?.id ?? null,
      };
    }),
    ...[
      ...buildLoadingFeeExpenses(data.driverSales, driverById, user.id, fixedPricing.truckLoadingFeePerBag),
      ...buildTruckCostExpenses(
        data.truckDeliveries,
        truckCustomerById,
        fixedPricing.truckLoadingFeePerBag,
        fixedPricing.truckOffloadingFeePerBag,
        fixedPricing.truckHiredCostPerBag,
        user.id
      ),
    ].map((e) => ({
      description: e.description,
      amount: e.amount,
      paid: e.paid,
      rollsKg: null,
      packingBagsBundles: null,
      packingBagTypeId: null,
    })),
  ];

  try {
    await prisma.$transaction(
      async (tx) => {
        await tx.productionLine.deleteMany({ where: { dailyRecordId: id } });
        await tx.driverSale.deleteMany({ where: { dailyRecordId: id } });
        await tx.truckDelivery.deleteMany({ where: { dailyRecordId: id } });
        // Expense lines are synced (not wiped) after the record update below,
        // so payments already recorded against them survive the edit.

        await tx.dailyRecord.update({
          where: { id },
          data: {
            lastEditedById: user.id,
            lastEditedAt: new Date(),
            date: data.date,
            openingStock: opening,
            closingStock: closing,
            factoryBags: data.factoryBags,
            factoryBagsFromLeakage: data.factoryBagsFromLeakage,
            factoryPricePerBag,
            factoryCustomerId: data.factoryCustomerId || null,
            pumpWaterAmount: data.pumpWaterAmount,
            bankAccountId: newBankAccountId,
            bankAmountSent: newBankAmountSent,
            ...(bankDetailsChanged
              ? { bankMoneyReceived: false, bankReceivedAt: null, bankReceivedById: null }
              : {}),
            leakageOpening,
            leakageBags: data.leakageBags,
            leakageWasteBags: data.leakageWasteBags,
            leakageClosing,
            productionLines: {
              create: data.production.map((p) => {
                const packer = packerByName.get(p.packerName.trim().toLowerCase());
                return { packerId: packer!.id, bags: p.bags, pricePerBag: fixedPricing.packerPricePerBag };
              }),
            },
            driverSales: {
              create: data.driverSales.map((d) => {
                const driver = driverById.get(d.driverId);
                return {
                  driverId: d.driverId,
                  bags: d.bags,
                  pricePerBag: driver?.pricePerBag ?? 0,
                  loadingFee: driver?.loadingFee ?? 0,
                  loadingFeeWaived: d.loadingFeeWaived,
                  bonusBags: d.bonusBags,
                  bagsFromLeakage: d.bagsFromLeakage,
                };
              }),
            },
            truckDeliveries: {
              create: data.truckDeliveries.map((t) => {
                const customer = truckCustomerById.get(t.customerId);
                return {
                  customerId: t.customerId,
                  bags: t.bags,
                  bonusBags: t.bonusBags,
                  pricePerBag: customer?.pricePerBag ?? 0,
                  ownTruck: t.ownTruck,
                  fuelCost: t.ownTruck ? t.fuelCost : 0,
                  hiredCost: !t.ownTruck && !t.hiredCostWaived ? t.bags * fixedPricing.truckHiredCostPerBag : 0,
                  hiredCostPerBag: t.ownTruck ? 0 : fixedPricing.truckHiredCostPerBag,
                  hiredCostWaived: t.hiredCostWaived,
                  loadingFeePerBag: fixedPricing.truckLoadingFeePerBag,
                  loadingFeeWaived: t.loadingFeeWaived,
                  offloadingFeePerBag: fixedPricing.truckOffloadingFeePerBag,
                  offloadingFeeWaived: t.offloadingFeeWaived,
                  bagsFromLeakage: t.bagsFromLeakage,
                };
              }),
            },
          },
        });

        await syncExpenseItems(tx, id, desiredExpenses, user.id);

        if (existing.status === "APPROVED") {
          if (dateChanged) {
            const boundaryDate = existing.date < data.date ? existing.date : data.date;
            const anchor = await tx.dailyRecord.findFirst({
              where: { status: "APPROVED", archivedAt: null, date: { lt: boundaryDate }, id: { not: id } },
              orderBy: { date: "desc" },
            });
            await cascadeRecalculate(
              tx,
              anchor?.date ?? "",
              anchor?.closingStock ?? 0,
              anchor?.leakageClosing ?? 0,
              overrideApplied ? id : undefined
            );
          } else {
            await cascadeRecalculate(tx, existing.date, closing, leakageClosing);
          }
        }
      },
      { timeout: 20000 }
    );
  } catch (e) {
    if (e instanceof Prisma.PrismaClientKnownRequestError && e.code === "P2002") {
      return { ok: false, error: `A daily record for ${data.date} already exists.` };
    }
    throw e;
  }

  await logActivity(
    dateChanged
      ? `${user.name} edited the daily record and moved its date from ${existing.date} to ${data.date}.`
      : `${user.name} edited the daily record for ${existing.date}.`,
    user.id
  );
  if (user.id !== existing.createdById) {
    after(() =>
      sendPushToUsers([existing.createdById], {
        title: "Your daily record was updated",
        body: `${user.name} made changes to your daily record for ${data.date}.`,
        url: "/daily-record",
      })
    );
  }
  revalidatePath("/", "layout");
  return { ok: true };
}

export type IncentiveStockSource = "FRESH" | "LEAKAGE";

export interface IncentiveAwardResult {
  ok: boolean;
  error?: string;
}

/**
 * Approves a customer/driver's weekly incentive bonus (crossing the
 * 500/1000-bag threshold) and deducts it from stock — on TODAY's daily
 * record if logged, otherwise the most recent approved record (never the
 * day the threshold was actually reached). The bonus is earned once per full threshold
 * reached that week, so a week may get several IncentiveAward rows (a
 * top-up when a further threshold is crossed after an earlier approval);
 * their sum is the idempotency guard (never more than what was earned) and
 * each row is the audit trail of who approved it.
 */
export async function approveIncentiveAward(
  entityType: "CUSTOMER" | "DRIVER",
  entityId: string,
  weekKey: string,
  source: IncentiveStockSource = "FRESH"
): Promise<IncentiveAwardResult> {
  const guard = await requireRoleSafe(["ADMIN", "SUPER_ADMIN"]);
  if (source !== "FRESH" && source !== "LEAKAGE") return { ok: false, error: "Invalid stock source." };
  if (!guard.ok) return { ok: false, error: guard.error };
  const admin = guard.user;

  // Past weeks are allowed (late payout of a missed bonus) — only future weeks are rejected.
  if (!/^\d{4}-W\d+$/.test(weekKey) || weekKey.localeCompare(currentWeekKey(), undefined, { numeric: true }) > 0) {
    return { ok: false, error: "Invalid week." };
  }
  const isPastWeek = weekKey !== currentWeekKey();
  if (isLegacyDriverBonusWeek(entityType, weekKey)) {
    return { ok: false, error: "This driver's bonus for that week was already given before approvals were tracked." };
  }

  // All-time records (ignoring archives), so a past week that's since been archived still counts.
  const [weeklySettings, approvedRecords, entity, existingAwards] = await Promise.all([
    getWeeklyIncentiveSettings(),
    getAllApprovedRecordsEverSorted(),
    entityType === "CUSTOMER"
      ? prisma.customer.findUnique({ where: { id: entityId } })
      : prisma.driver.findUnique({ where: { id: entityId } }),
    prisma.incentiveAward.findMany({
      where: {
        entityType,
        weekKey,
        ...(entityType === "CUSTOMER" ? { customerId: entityId } : { driverId: entityId }),
      },
    }),
  ]);
  if (!entity) return { ok: false, error: "Not found." };

  const { customerWeekly, driverWeekly } = computeIncentiveData(approvedRecords);
  const weeklyBags =
    entityType === "CUSTOMER" ? (customerWeekly.get(entityId)?.[weekKey] ?? 0) : (driverWeekly.get(entityId)?.[weekKey] ?? 0);
  const threshold = entityType === "CUSTOMER" ? weeklySettings.customerWeeklyThreshold : weeklySettings.driverWeeklyThreshold;
  const bonusPerThreshold = entityType === "CUSTOMER" ? weeklySettings.customerWeeklyBonus : weeklySettings.driverWeeklyBonus;
  if (weeklyBags < threshold) {
    return {
      ok: false,
      error: isPastWeek
        ? `"${entity.name}" didn't reach the weekly threshold in ${weekKey}.`
        : `"${entity.name}" doesn't currently qualify for the weekly bonus.`,
    };
  }
  // Bonus is per full threshold reached (2000 bags on 1000 = 2×). Only the part
  // not yet approved is deducted, so a week can be topped up but never paid twice.
  const earnedBags = weeklyThresholdBonus(weeklyBags, threshold, bonusPerThreshold);
  const alreadyReceived = existingAwards.reduce((s, a) => s + a.bonusBags, 0);
  const bonusBags = earnedBags - alreadyReceived;
  if (bonusBags <= 0) {
    return { ok: false, error: "This bonus has already been approved." };
  }

  // Deduct on today's approved record, or if today isn't logged/approved yet,
  // the most recent approved record — so approving is never blocked on a
  // missing day. That record's date is what's tracked as the deduction date.
  // Every later day (approved or pending) is then recalculated, so each next
  // opening stock and Current Stock carry it forward.
  const today = todayISO();
  const targetRecord = await prisma.dailyRecord.findFirst({
    where: { status: "APPROVED", archivedAt: null, date: { lte: today } },
    orderBy: { date: "desc" },
  });
  if (!targetRecord) {
    return { ok: false, error: "There's no approved daily record yet to deduct this bonus from." };
  }
  if (targetRecord.archivedAt) {
    return { ok: false, error: "That record is archived — can't adjust its stock." };
  }
  const deductionDay = targetRecord.date;
  const dayLabel = deductionDay === today ? "today" : deductionDay;

  const fromLeakage = source === "LEAKAGE";
  if (fromLeakage && targetRecord.leakageClosing < bonusBags) {
    return {
      ok: false,
      error: `Only ${targetRecord.leakageClosing} bags are left in the leakage pile (${dayLabel}) — not enough for this ${bonusBags}-bag bonus.`,
    };
  }
  const newClosing = fromLeakage ? targetRecord.closingStock : targetRecord.closingStock - bonusBags;
  const newLeakageClosing = fromLeakage ? targetRecord.leakageClosing - bonusBags : targetRecord.leakageClosing;

  await prisma.$transaction(async (tx) => {
    await tx.dailyRecord.update({
      where: { id: targetRecord.id },
      data: fromLeakage
        ? { leakageClosing: newLeakageClosing, incentiveBonusBagsFromLeakage: { increment: bonusBags } }
        : { closingStock: newClosing, incentiveBonusBags: { increment: bonusBags } },
    });
    await tx.incentiveAward.create({
      data: {
        entityType,
        weekKey,
        bonusBags,
        source,
        customerId: entityType === "CUSTOMER" ? entityId : null,
        driverId: entityType === "DRIVER" ? entityId : null,
        dailyRecordId: targetRecord.id,
        approvedById: admin.id,
      },
    });
    await cascadeRecalculate(tx, deductionDay, newClosing, newLeakageClosing, targetRecord.id);
  });

  await logActivity(
    `${admin.name} approved the weekly incentive bonus (+${bonusBags} bags) for "${entity.name}"${isPastWeek ? ` for past week ${weekKey} (late payout)` : ""} — deducted from ${dayLabel === "today" ? "today's" : `the ${dayLabel} record's`} ${fromLeakage ? "leakage pile" : "available stock"}.`,
    admin.id
  );
  revalidatePath("/", "layout");
  return { ok: true };
}

/** Undoes an incentive award — deletes it and adds the bonus bags back to the pile (fresh or leakage) they came from, on the day they were deducted. */
export async function revertIncentiveAward(awardId: string): Promise<IncentiveAwardResult> {
  const guard = await requireRoleSafe(["ADMIN", "SUPER_ADMIN"]);
  if (!guard.ok) return { ok: false, error: guard.error };
  const admin = guard.user;

  const award = await prisma.incentiveAward.findUnique({
    where: { id: awardId },
    include: { customer: true, driver: true, dailyRecord: true },
  });
  if (!award) return { ok: false, error: "Award not found." };
  if (award.dailyRecord.archivedAt) {
    return { ok: false, error: "That day's record is archived — can't adjust its stock." };
  }

  const entityName = award.customer?.name ?? award.driver?.name ?? "Unknown";
  const fromLeakage = award.source === "LEAKAGE";
  const newClosing = fromLeakage ? award.dailyRecord.closingStock : award.dailyRecord.closingStock + award.bonusBags;
  const newLeakageClosing = fromLeakage
    ? award.dailyRecord.leakageClosing + award.bonusBags
    : award.dailyRecord.leakageClosing;

  await prisma.$transaction(async (tx) => {
    await tx.incentiveAward.delete({ where: { id: awardId } });
    await tx.dailyRecord.update({
      where: { id: award.dailyRecordId },
      data: fromLeakage
        ? { leakageClosing: newLeakageClosing, incentiveBonusBagsFromLeakage: { decrement: award.bonusBags } }
        : { closingStock: newClosing, incentiveBonusBags: { decrement: award.bonusBags } },
    });
    await cascadeRecalculate(tx, award.dailyRecord.date, newClosing, newLeakageClosing, award.dailyRecordId);
  });

  await logActivity(
    `${admin.name} reverted the weekly incentive bonus (+${award.bonusBags} bags) for "${entityName}" (${award.weekKey}) — added back to ${fromLeakage ? "the leakage pile" : "available stock"}.`,
    admin.id
  );
  revalidatePath("/", "layout");
  return { ok: true };
}

export interface DeleteDailyRecordResult {
  ok: boolean;
  error?: string;
}

/**
 * Moves a record to the trash and undoes everything it did. Most of a
 * record's effects are derived from it on the fly — stock & leakage chain,
 * bank account balance (deposit + auto-debited expenses), packer pay owed,
 * customer/driver incentive totals, reports — so removing it reverts them.
 * The one stored side effect, weekly bonuses approved and deducted on that
 * day, is reverted explicitly (and brought back on restore). A full copy is
 * kept in the trash with a written list of what was undone.
 */
export async function deleteDailyRecord(id: string): Promise<DeleteDailyRecordResult> {
  const guard = await requireRoleSafe(["ADMIN", "SUPER_ADMIN"]);
  if (!guard.ok) return { ok: false, error: guard.error };
  const user = guard.user;

  const existing = await prisma.dailyRecord.findUnique({
    where: { id },
    include: {
      productionLines: true,
      driverSales: true,
      truckDeliveries: true,
      expenseItems: { include: { payments: true } },
      incentiveAwards: true,
    },
  });
  if (!existing) {
    return { ok: false, error: "Daily record not found." };
  }
  if (existing.archivedAt) {
    return { ok: false, error: "This record is archived and read-only." };
  }

  const effects = await describeRecordEffects(id);

  await prisma.$transaction(
    async (tx) => {
      await tx.trashedDailyRecord.create({
        data: {
          originalId: existing.id,
          date: existing.date,
          status: existing.status,
          snapshot: JSON.parse(JSON.stringify(existing)),
          effects,
          deletedById: user.id,
        },
      });
      // Bonus awards point at this record without cascading — remove them
      // first. Their stock deduction lived on this record, so it goes with it.
      await tx.incentiveAward.deleteMany({ where: { dailyRecordId: id } });
      await tx.dailyRecord.delete({ where: { id } });
      if (existing.status === "APPROVED") {
        const prev = await tx.dailyRecord.findFirst({
          where: { status: "APPROVED", archivedAt: null, date: { lt: existing.date } },
          orderBy: { date: "desc" },
        });
        await cascadeRecalculate(tx, existing.date, prev?.closingStock ?? 0, prev?.leakageClosing ?? 0);
      }
    },
    { timeout: 20000 }
  );

  await logActivity(
    `${user.name} moved the daily record for ${existing.date} to the trash. Reverted: ${effects.join(" ")}`,
    user.id
  );
  revalidatePath("/", "layout");
  return { ok: true };
}

/**
 * Plain-language list of what a record does to the rest of the system —
 * stored with its trash entry as the trace of what trashing reverted, and
 * shown again before a restore as what will come back.
 */
async function describeRecordEffects(id: string): Promise<string[]> {
  const r = await prisma.dailyRecord.findUniqueOrThrow({
    where: { id },
    include: {
      productionLines: { include: { packer: { select: { name: true } } } },
      driverSales: { include: { driver: { select: { name: true } }, customer: { select: { name: true } } } },
      truckDeliveries: { include: { customer: { select: { name: true } } } },
      expenseItems: { select: { amount: true, amountPaid: true } },
      factoryCustomer: { select: { name: true } },
      bankAccount: { select: { bankName: true, accountName: true } },
      incentiveAwards: { include: { customer: { select: { name: true } }, driver: { select: { name: true } } } },
    },
  });
  const approved = r.status === "APPROVED";
  const out: string[] = [];
  const bags = (n: number) => `${n} bag${n === 1 ? "" : "s"}`;

  const produced = r.productionLines.reduce((s, p) => s + p.bags, 0);
  const driverBags = r.driverSales.reduce((s, d) => s + d.bags + d.bonusBags, 0);
  const truckBags = r.truckDeliveries.reduce((s, t) => s + t.bags + t.bonusBags, 0);
  const sold = r.factoryBags + driverBags + truckBags;
  if (approved) {
    const later = await prisma.dailyRecord.count({ where: { archivedAt: null, date: { gt: r.date } } });
    out.push(
      `Stock: ${bags(produced)} produced and ${bags(sold)} sold or given out` +
        (later > 0 ? ` — opening/closing stock recalculated on ${later} later record${later === 1 ? "" : "s"}.` : ".")
    );
    if (r.leakageBags || r.leakageWasteBags || r.factoryBagsFromLeakage) {
      out.push(
        `Leakage balance: ${bags(r.leakageBags)} new leakage, ${bags(r.leakageWasteBags)} wasted, ${bags(r.factoryBagsFromLeakage)} factory-sold from leakage.`
      );
    }
  } else {
    out.push(
      `Stock: none — the record was ${r.status.toLowerCase()}, so it hadn't touched stock (${bags(produced)} produced, ${bags(sold)} sold).`
    );
  }

  const income =
    r.factoryBags * r.factoryPricePerBag +
    r.pumpWaterAmount +
    r.driverSales.reduce((s, d) => s + d.bags * d.pricePerBag, 0) +
    r.truckDeliveries.reduce((s, t) => s + t.bags * t.pricePerBag, 0);
  if (income > 0) out.push(`Income: ${formatMoney(income)} of sales in reports and totals.`);

  if (r.expenseItems.length > 0) {
    const total = r.expenseItems.reduce((s, e) => s + e.amount, 0);
    const paid = r.expenseItems.reduce((s, e) => s + e.amountPaid, 0);
    out.push(
      `Expenses: ${r.expenseItems.length} line${r.expenseItems.length === 1 ? "" : "s"} totalling ${formatMoney(total)} (${formatMoney(paid)} marked paid, with payment history)${approved ? ", including the default account's debits" : ""}.`
    );
  }

  if (r.bankAccount && r.bankAmountSent > 0) {
    out.push(
      `Bank: ${formatMoney(r.bankAmountSent)} ${r.bankMoneyReceived ? "confirmed" : "expected"} deposit to ${r.bankAccount.bankName} — ${r.bankAccount.accountName}${approved ? " (counts in its balance)" : ""}.`
    );
  }

  const byPacker = new Map<string, number>();
  for (const p of r.productionLines) {
    byPacker.set(p.packer.name, (byPacker.get(p.packer.name) ?? 0) + p.bags * p.pricePerBag);
  }
  const pay = [...byPacker].filter(([, amt]) => amt > 0).map(([name, amt]) => `${name} ${formatMoney(amt)}`);
  if (pay.length > 0) {
    out.push(`Packer pay owed: ${pay.join(", ")} (payments already made to packers are never changed).`);
  }

  if (approved) {
    const credited = new Map<string, number>();
    const add = (name: string | undefined, n: number) => {
      if (name && n > 0) credited.set(name, (credited.get(name) ?? 0) + n);
    };
    for (const d of r.driverSales) {
      add(d.driver.name, d.bags);
      add(d.customer?.name, d.bags);
    }
    for (const t of r.truckDeliveries) add(t.customer?.name, t.bags);
    add(r.factoryCustomer?.name, r.factoryBags);
    if (credited.size > 0) {
      out.push(`Incentive bag totals: ${[...credited].map(([name, n]) => `${name} ${bags(n)}`).join(", ")}.`);
    }
  }

  for (const a of r.incentiveAwards) {
    out.push(
      `Weekly bonus: ${bags(a.bonusBags)} for ${a.customer?.name ?? a.driver?.name ?? "unknown"} (${a.weekKey}), from ${a.source === "LEAKAGE" ? "the leakage pile" : "available stock"} — marked received.`
    );
  }
  return out;
}

/** Shape of TrashedDailyRecord.snapshot — a DailyRecord with its child rows, JSON-serialised (dates as ISO strings). */
type TrashSnapshot = Record<string, unknown> & {
  incentiveBonusBags?: number;
  incentiveBonusBagsFromLeakage?: number;
  productionLines: Record<string, unknown>[];
  driverSales: Record<string, unknown>[];
  truckDeliveries: Record<string, unknown>[];
  expenseItems: (Record<string, unknown> & { payments: Record<string, unknown>[] })[];
  incentiveAwards?: (Record<string, unknown> & {
    customerId: string | null;
    driverId: string | null;
    weekKey: string;
    bonusBags: number;
    source: string;
  })[];
};

function withoutKeys<T extends Record<string, unknown>>(obj: T, keys: string[]) {
  const copy: Record<string, unknown> = { ...obj };
  for (const k of keys) delete copy[k];
  return copy;
}

export interface RestorePreview {
  ok: boolean;
  error?: string;
  date?: string;
  /** Everything that comes back with the record. */
  restores?: string[];
  /** Notes about things that will NOT come back, and why. */
  notes?: string[];
  /** Reasons the restore can't go ahead at all. */
  blockers?: string[];
}

type TrashedRow = { id: string; date: string; deletedAt: Date; restoredAt: Date | null; snapshot: unknown; effects: unknown };

const RECORD_ITSELF_LINE =
  "The record itself — production, driver sales, truck deliveries, leakages, expenses and their payments, exactly as they were.";

function fmtDateTime(d: Date): string {
  return d.toLocaleString("en-NG", { day: "numeric", month: "short", year: "numeric", hour: "numeric", minute: "2-digit" });
}

async function planRestore(trashed: TrashedRow) {
  const snap = trashed.snapshot as TrashSnapshot;
  const blockers: string[] = [];
  const notes: string[] = [];
  if (trashed.restoredAt) {
    blockers.push(`This record was already restored on ${fmtDateTime(trashed.restoredAt)}.`);
  }

  const [sameDate, archivedSince] = await Promise.all([
    prisma.dailyRecord.findUnique({ where: { date: trashed.date }, select: { id: true } }),
    prisma.dailyRecord.findFirst({ where: { archivedAt: { gt: trashed.deletedAt } }, select: { id: true } }),
  ]);
  if (sameDate) {
    blockers.push(`${formatDay(trashed.date)} already has a new record. Trash or move that one first if you want this one back.`);
  }
  if (archivedSince) {
    blockers.push("The recording session was archived after this record was trashed, so it can't go back into the current session.");
  }

  // A weekly bonus for the same person and week approved again since the
  // trash would be paid twice if this one came back too — leave it out.
  const awards = snap.incentiveAwards ?? [];
  const keep: typeof awards = [];
  for (const a of awards) {
    const again = await prisma.incentiveAward.findFirst({
      where: {
        weekKey: a.weekKey,
        ...(a.customerId ? { customerId: a.customerId } : { driverId: a.driverId }),
      },
      include: { customer: { select: { name: true } }, driver: { select: { name: true } } },
    });
    if (again) {
      notes.push(
        `Weekly bonus of ${a.bonusBags} bags for ${again.customer?.name ?? again.driver?.name ?? "that person"} (${a.weekKey}) won't come back — that week's bonus was approved again after this record was trashed.`
      );
    } else {
      keep.push(a);
    }
  }

  const restores = Array.isArray(trashed.effects) ? (trashed.effects as string[]) : [];
  const restoresShown = restores.filter(
    (line) => !line.startsWith("Weekly bonus:") || keep.some((a) => line.includes(`(${a.weekKey})`))
  );
  return {
    snap,
    blockers,
    notes,
    keepAwards: keep,
    skippedAwards: awards.filter((a) => !keep.includes(a)),
    restores: [RECORD_ITSELF_LINE, ...restoresShown],
  };
}

/** What restoring would bring back (and anything that stops it) — shown for confirmation first. */
export async function getRestorePreview(trashId: string): Promise<RestorePreview> {
  const guard = await requireRoleSafe(["ADMIN", "SUPER_ADMIN"]);
  if (!guard.ok) return { ok: false, error: guard.error };
  const trashed = await prisma.trashedDailyRecord.findUnique({ where: { id: trashId } });
  if (!trashed) return { ok: false, error: "That record is no longer in the trash." };
  const plan = await planRestore(trashed);
  return { ok: true, date: trashed.date, restores: plan.restores, notes: plan.notes, blockers: plan.blockers };
}

/**
 * Puts a trashed record back exactly as it was (same id, rows, payments,
 * weekly bonuses deducted that day), then re-runs the stock chain from it.
 */
export async function restoreTrashedDailyRecord(trashId: string): Promise<{ ok: boolean; error?: string }> {
  const guard = await requireRoleSafe(["ADMIN", "SUPER_ADMIN"]);
  if (!guard.ok) return { ok: false, error: guard.error };
  const user = guard.user;

  const trashed = await prisma.trashedDailyRecord.findUnique({ where: { id: trashId } });
  if (!trashed) return { ok: false, error: "That record is no longer in the trash." };

  const plan = await planRestore(trashed);
  if (plan.blockers.length > 0) return { ok: false, error: plan.blockers.join(" ") };
  const { snap } = plan;

  // Bonuses left out still have their bags counted on the record — take them off.
  let bonusFresh = snap.incentiveBonusBags ?? 0;
  let bonusLeakage = snap.incentiveBonusBagsFromLeakage ?? 0;
  for (const a of plan.skippedAwards) {
    if (a.source === "LEAKAGE") bonusLeakage = Math.max(0, bonusLeakage - a.bonusBags);
    else bonusFresh = Math.max(0, bonusFresh - a.bonusBags);
  }

  const restoredAt = new Date();
  const record = withoutKeys(snap, [
    "productionLines",
    "driverSales",
    "truckDeliveries",
    "expenseItems",
    "incentiveAwards",
    "updatedAt",
  ]);

  try {
    await prisma.$transaction(
      async (tx) => {
        await tx.dailyRecord.create({
          data: {
            ...(record as Prisma.DailyRecordUncheckedCreateInput),
            incentiveBonusBags: bonusFresh,
            incentiveBonusBagsFromLeakage: bonusLeakage,
            productionLines: { create: snap.productionLines.map((p) => withoutKeys(p, ["dailyRecordId"])) as never },
            driverSales: { create: snap.driverSales.map((d) => withoutKeys(d, ["dailyRecordId"])) as never },
            truckDeliveries: { create: snap.truckDeliveries.map((t) => withoutKeys(t, ["dailyRecordId"])) as never },
            expenseItems: {
              create: snap.expenseItems.map((e) => ({
                ...withoutKeys(e, ["dailyRecordId", "payments"]),
                payments: { create: e.payments.map((p) => withoutKeys(p, ["expenseItemId"])) },
              })) as never,
            },
            incentiveAwards: { create: plan.keepAwards.map((a) => withoutKeys(a, ["dailyRecordId"])) as never },
          },
        });
        const prev = await tx.dailyRecord.findFirst({
          where: { status: "APPROVED", archivedAt: null, date: { lt: trashed.date } },
          orderBy: { date: "desc" },
        });
        await cascadeRecalculate(tx, prev?.date ?? "", prev?.closingStock ?? 0, prev?.leakageClosing ?? 0);
        // Keep the entry as history of the restore rather than removing it.
        await tx.trashedDailyRecord.update({
          where: { id: trashId },
          data: {
            restoredAt,
            restoredById: user.id,
            restoredItems: plan.restores,
            notRestoredItems: plan.notes,
          },
        });
      },
      { timeout: 20000 }
    );
  } catch (err) {
    console.error("restoreTrashedDailyRecord failed", err);
    return {
      ok: false,
      error:
        "Couldn't restore this record — something it refers to (a driver, customer, packer, bank account or user) may have been deleted since.",
    };
  }

  await logActivity(
    `${user.name} restored the daily record for ${formatDay(trashed.date)} from the trash on ${fmtDateTime(restoredAt)} (trashed ${fmtDateTime(trashed.deletedAt)}). Restored: ${plan.restores.join(" ")}${plan.notes.length ? ` Not restored: ${plan.notes.join(" ")}` : ""}`,
    user.id
  );
  revalidatePath("/", "layout");
  return { ok: true };
}

/** Removes a trashed record for good. Super Admin only. */
export async function purgeTrashedDailyRecord(trashId: string): Promise<{ ok: boolean; error?: string }> {
  const guard = await requireRoleSafe(["SUPER_ADMIN"]);
  if (!guard.ok) return { ok: false, error: guard.error };
  const trashed = await prisma.trashedDailyRecord.findUnique({ where: { id: trashId } });
  if (!trashed) return { ok: false, error: "That record is no longer in the trash." };
  await prisma.trashedDailyRecord.delete({ where: { id: trashId } });
  await logActivity(`${guard.user.name} permanently deleted the trashed daily record for ${trashed.date}.`, guard.user.id);
  revalidatePath("/daily-record");
  return { ok: true };
}

export interface ArchiveRecordsResult {
  ok: boolean;
  error?: string;
  archivedCount?: number;
}

/**
 * Archives every currently-active daily record so a fresh recording session
 * can start — nothing is deleted, archived records stay fully intact and
 * viewable on the Archive tab, just out of the active views (Daily Record
 * table, Dashboard, stock chain, weekly incentive progress). The next new
 * record's opening stock therefore starts from 0 (Super Admin re-enters the
 * real physical count), while yearly customer/driver incentive totals keep
 * counting straight through, since getAllApprovedRecordsEverSorted() ignores
 * archive state.
 */
export async function archiveAllActiveRecords(): Promise<ArchiveRecordsResult> {
  const guard = await requireRoleSafe(["SUPER_ADMIN"]);
  if (!guard.ok) return { ok: false, error: guard.error };
  const admin = guard.user;

  const activeCount = await prisma.dailyRecord.count({ where: { archivedAt: null } });
  if (activeCount === 0) {
    return { ok: false, error: "There are no active records to archive." };
  }

  await prisma.dailyRecord.updateMany({
    where: { archivedAt: null },
    data: { archivedAt: new Date(), archivedById: admin.id },
  });

  await logActivity(
    `${admin.name} archived ${activeCount} daily record${activeCount === 1 ? "" : "s"} and started a new recording session.`,
    admin.id
  );
  revalidatePath("/", "layout");
  return { ok: true, archivedCount: activeCount };
}

