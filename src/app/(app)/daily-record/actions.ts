function isAdminRole(role: string) {
  return role === "ADMIN" || role === "SUPER_ADMIN";
}

/**
 * A record that only has production on it — what the Total Produced page's
 * quick-add creates. "New daily entry" may continue one of these; any other
 * existing record blocks New entry for that date (use its Edit button).
 */
function isProductionOnly(r: {
  factoryBags: number;
  pumpWaterAmount: number;
  leakageBags: number;
  leakageWasteBags: number;
  bankAccountId: string | null;
  driverSales: unknown[];
  truckDeliveries: unknown[];
  expenseItems: unknown[];
}): boolean {
  return (
    r.factoryBags === 0 &&
    r.pumpWaterAmount === 0 &&
    r.leakageBags === 0 &&
    r.leakageWasteBags === 0 &&
    r.bankAccountId === null &&
    r.driverSales.length === 0 &&
    r.truckDeliveries.length === 0 &&
    r.expenseItems.length === 0
  );
}

/** Earlier days that saving a record on `date` would leave unfilled — for the form's live warning. */
export async function checkUnfilledDates(date: string, recordId?: string): Promise<UnfilledDates> {
  await requireUser();
  const none = { missing: [], pending: [] };
  if (!/^\d{4}-\d{2}-\d{2}$/.test(date)) return none;
  if (!recordId) return findUnfilledDates(date);
  const rec = await prisma.dailyRecord.findUnique({ where: { id: recordId }, select: { date: true } });
  if (!rec || rec.date === date) return none;
  return findUnfilledDates(date, { excludeId: recordId, oldDate: rec.date });
}

export async function markWorkFreeDays(dates: string[], reason?: string): Promise<{ ok: boolean; error?: string }> {
  const guard = await requireRoleSafe(["ADMIN", "SUPER_ADMIN"]);
  if (!guard.ok) return { ok: false, error: guard.error };
  const user = guard.user;
  const unique = [...new Set(dates)].filter((d) => /^\d{4}-\d{2}-\d{2}$/.test(d));
  if (unique.length === 0) return { ok: false, error: "Pick a date." };
  const recorded = await prisma.dailyRecord.findMany({
    where: { date: { in: unique }, archivedAt: null },
    select: { date: true },
  });
  if (recorded.length > 0) {
    return {
      ok: false,
      error: `${recorded.map((r) => formatDay(r.date)).join(", ")} already ${recorded.length === 1 ? "has a" : "have"} daily record${recorded.length === 1 ? "" : "s"} — can't mark as work-free.`,
    };
  }
  const trimmedReason = reason?.trim().slice(0, 120) || null;
  await prisma.workFreeDay.createMany({
    data: unique.map((date) => ({ date, reason: trimmedReason, createdById: user.id })),
    skipDuplicates: true,
  });
  await logActivity(
    `${user.name} marked ${unique.map(formatDay).join(", ")} as work-free${trimmedReason ? ` (${trimmedReason})` : ""}.`,
    user.id
  );
  revalidatePath("/daily-record");
  return { ok: true };
}

export async function unmarkWorkFreeDay(id: string): Promise<{ ok: boolean; error?: string }> {
  const guard = await requireRoleSafe(["ADMIN", "SUPER_ADMIN"]);
  if (!guard.ok) return { ok: false, error: guard.error };
  const day = await prisma.workFreeDay.findUnique({ where: { id } });
  if (!day) return { ok: false, error: "Work-free day not found." };
  await prisma.workFreeDay.delete({ where: { id } });
  await logActivity(`${guard.user.name} removed the work-free mark on ${formatDay(day.date)}.`, guard.user.id);
  revalidatePath("/daily-record");
  return { ok: true };
}

export async function createDailyRecord(input: unknown): Promise<CreateDailyRecordResult> {
  const guard = await requireRoleSafe([
    "SALES_STAFF",
    // "EDITOR", // disabled for now
    "ADMIN_STAFF",
    "ADMIN",
    "SUPER_ADMIN",
  ]);
  if (!guard.ok) return { ok: false, error: guard.error };
  const user = guard.user;
  const parsed = dailyRecordSchema.safeParse(input);
  if (!parsed.success) {
    return { ok: false, error: parsed.error.issues[0]?.message ?? "Invalid input" };
  }
  const data = parsed.data;

  const existing = await prisma.dailyRecord.findUnique({ where: { date: data.date } });
  if (existing) {
    return { ok: false, error: `A daily record for ${data.date} already exists.` };
  }

  const unfilled = await findUnfilledDates(data.date);
  if (hasUnfilled(unfilled)) {
    return { ok: false, error: unfilledDatesMessage(unfilled, isAdminRole(user.role)), unfilled };
  }

  const [computedOpening, computedLeakageOpening, fixedPricing, packingBagTypes, drivers, truckCustomers, packerByName] =
    await Promise.all([
      latestClosingStock(),
      latestLeakageClosing(),
      getPricingSettings(),
      getPackingBagTypes(),
      prisma.driver.findMany({ where: { id: { in: data.driverSales.map((d) => d.driverId) } } }),
      prisma.customer.findMany({
        where: { id: { in: data.truckDeliveries.map((t) => t.customerId) } },
      }),
      resolvePackers(
        data.production.map((p) => p.packerName),
        user.id
      ),
    ]);

  const opening =
    user.role === "SUPER_ADMIN" && data.openingStockOverride != null ? data.openingStockOverride : computedOpening;
  const leakageOpening =
    user.role === "SUPER_ADMIN" && data.leakageOpeningOverride != null
      ? data.leakageOpeningOverride
      : computedLeakageOpening;

  const rowError = validateBagsFromLeakagePerRow(data.driverSales, data.truckDeliveries);
  if (rowError) return { ok: false, error: rowError };

  const driverTruckBagsFromLeakageTotal =
    data.driverSales.reduce((s, d) => s + d.bagsFromLeakage, 0) +
    data.truckDeliveries.reduce((s, t) => s + t.bagsFromLeakage, 0);

  // Today's new leakage can be rebagged (and sold or wasted) the same day, so it counts as available.
  const leakageAvailable = leakageOpening + data.leakageBags;
  if (data.factoryBagsFromLeakage + driverTruckBagsFromLeakageTotal + data.leakageWasteBags > leakageAvailable) {
    return {
      ok: false,
      error: `Only ${leakageAvailable} bags are available in the leakage pile to sell, rebag, or waste (${leakageOpening} carried over + ${data.leakageBags} new today).`,
    };
  }

  const prodTotal = data.production.reduce((s, p) => s + p.bags, 0);
  const driverBagsTotal = data.driverSales.reduce((s, d) => s + d.bags, 0);
  const driverBonusBagsTotal = data.driverSales.reduce((s, d) => s + d.bonusBags, 0);
  const truckDeliveryBagsTotal = data.truckDeliveries.reduce((s, t) => s + t.bags, 0);
  const truckDeliveryBonusBagsTotal = data.truckDeliveries.reduce((s, t) => s + t.bonusBags, 0);

  const computedClosing = computeClosingStock({
    opening,
    prodTotal,
    factoryBags: data.factoryBags,
    factoryBagsFromLeakage: data.factoryBagsFromLeakage,
    driverBagsTotal,
    driverBonusBagsTotal,
    truckDeliveryBagsTotal,
    truckDeliveryBonusBagsTotal,
    driverTruckBagsFromLeakage: driverTruckBagsFromLeakageTotal,
    leakageBagsNew: data.leakageBags,
  });
  const computedLeakageClosing = computeLeakageClosing(
    leakageOpening,
    data.leakageBags,
    data.factoryBagsFromLeakage,
    driverTruckBagsFromLeakageTotal,
    data.leakageWasteBags
  );
  const closing =
    user.role === "SUPER_ADMIN" && data.closingStockOverride != null ? data.closingStockOverride : computedClosing;
  const leakageClosing =
    user.role === "SUPER_ADMIN" && data.leakageClosingOverride != null
      ? data.leakageClosingOverride
      : computedLeakageClosing;
  const pending = needsApproval(user.role);

  const canEditFactoryPrice = user.role === "ADMIN" || user.role === "SUPER_ADMIN";
  const factoryPricePerBag = canEditFactoryPrice ? data.factoryPricePerBag : fixedPricing.factoryPricePerBag;
  const driverById = new Map(drivers.map((d) => [d.id, d]));
  const truckCustomerById = new Map(truckCustomers.map((c) => [c.id, c]));

  try {
    const record = await prisma.dailyRecord.create({
      data: {
        date: data.date,
        openingStock: opening,
        closingStock: closing,
        factoryBags: data.factoryBags,
        factoryBagsFromLeakage: data.factoryBagsFromLeakage,
        factoryPricePerBag,
        factoryCustomerId: data.factoryCustomerId || null,
        pumpWaterAmount: data.pumpWaterAmount,
        bankAccountId: data.bankAccountId || null,
        bankAmountSent: data.bankAccountId ? data.bankAmountSent : 0,
        leakageOpening,
        leakageBags: data.leakageBags,
        leakageWasteBags: data.leakageWasteBags,
        leakageClosing,
        status: pending ? "PENDING" : "APPROVED",
        createdById: user.id,
        createdByRole: user.role,
        approvedById: pending ? null : user.id,
        productionLines: {
          create: data.production.map((p) => {
            const packer = packerByName.get(p.packerName.trim().toLowerCase());
            return { packerId: packer!.id, bags: p.bags, pricePerBag: fixedPricing.packerPricePerBag };
          }),
        },
        driverSales: {
          create: data.driverSales.map((d) => {
            const driver = driverById.get(d.driverId);
            return {
              driverId: d.driverId,
              bags: d.bags,
              pricePerBag: driver?.pricePerBag ?? 0,
              loadingFee: driver?.loadingFee ?? 0,
              loadingFeeWaived: d.loadingFeeWaived,
              bonusBags: d.bonusBags,
              bagsFromLeakage: d.bagsFromLeakage,
            };
          }),
        },
        truckDeliveries: {
          create: data.truckDeliveries.map((t) => {
            const customer = truckCustomerById.get(t.customerId);
            return {
              customerId: t.customerId,
              bags: t.bags,
              bonusBags: t.bonusBags,
              pricePerBag: customer?.pricePerBag ?? 0,
              ownTruck: t.ownTruck,
              fuelCost: t.ownTruck ? t.fuelCost : 0,
              hiredCost: !t.ownTruck && !t.hiredCostWaived ? t.bags * fixedPricing.truckHiredCostPerBag : 0,
              hiredCostPerBag: t.ownTruck ? 0 : fixedPricing.truckHiredCostPerBag,
              hiredCostWaived: t.hiredCostWaived,
              loadingFeePerBag: fixedPricing.truckLoadingFeePerBag,
              loadingFeeWaived: t.loadingFeeWaived,
              offloadingFeePerBag: fixedPricing.truckOffloadingFeePerBag,
              offloadingFeeWaived: t.offloadingFeeWaived,
              bagsFromLeakage: t.bagsFromLeakage,
            };
          }),
        },
        expenseItems: {
          create: [
            ...data.expenses.map((e) => {
              const matchedType = matchPackingBagType(e.description, packingBagTypes);
              return {
                description: e.description,
                amount: e.amount,
                amountPaid: e.paid ? e.amount : 0,
                paid: e.paid,
                paidAt: e.paid ? new Date() : null,
                paidById: e.paid ? user.id : null,
                rollsKg:
                  isRollsExpense(e.description) && fixedPricing.rollsPricePerKg > 0
                    ? e.amount / fixedPricing.rollsPricePerKg
                    : null,
                packingBagsBundles: matchedType && matchedType.pricePerBundle > 0 ? e.amount / matchedType.pricePerBundle : null,
                packingBagTypeId: matchedType?.id ?? null,
              };
            }),
            ...buildLoadingFeeExpenses(data.driverSales, driverById, user.id, fixedPricing.truckLoadingFeePerBag),
            ...buildTruckCostExpenses(
              data.truckDeliveries,
              truckCustomerById,
              fixedPricing.truckLoadingFeePerBag,
              fixedPricing.truckOffloadingFeePerBag,
              fixedPricing.truckHiredCostPerBag,
              user.id
            ),
          ],
        },
      },
    });

    await logActivity(
      `${user.name} logged the daily record for ${record.date} (${pending ? "pending" : "approved"}).`,
      user.id
    );
    if (pending) {
      after(() =>
        notifyDailyRecordApprovers(
          {
            title: "New daily record awaiting approval",
            body: `${user.name} logged the record for ${record.date}.`,
            url: "/approvals",
          },
          user.id
        )
      );
    }
    revalidatePath("/", "layout");
    return { ok: true };
  } catch (e) {
    if (e instanceof Prisma.PrismaClientKnownRequestError && e.code === "P2002") {
      return { ok: false, error: `A daily record for ${data.date} already exists.` };
    }
    throw e;
  }
}

