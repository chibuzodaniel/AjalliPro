/** A row's leakage-sourced bags can never exceed the bags it's for. */
function validateBagsFromLeakagePerRow(
  driverSales: { bags: number; bagsFromLeakage: number }[],
  truckDeliveries: { bags: number; bagsFromLeakage: number }[]
): string | null {
  if (driverSales.some((d) => d.bagsFromLeakage > d.bags)) {
    return "A driver sale's \"from leakage\" bags can't exceed its own bags total.";
  }
  if (truckDeliveries.some((t) => t.bagsFromLeakage > t.bags)) {
    return "A truck delivery's \"from leakage\" bags can't exceed its own bags total.";
  }
  return null;
}

function buildLoadingFeeExpenses(
  driverSales: { driverId: string; bags: number; loadingFeeWaived: boolean; loadingFeePaid: boolean }[],
  driverById: Map<string, { name: string; loadingFee: number }>,
  paidById: string,
  // Falls back to the general per-bag loading fee (Settings) when this
  // specific driver has no loading fee of their own set.
  fallbackLoadingFeePerBag: number
) {
  const expenses: {
    description: string;
    amount: number;
    amountPaid: number;
    paid: boolean;
    paidAt: Date | null;
    paidById: string | null;
  }[] = [];
  for (const d of driverSales) {
    if (d.bags <= 0 || d.loadingFeeWaived) continue;
    const driver = driverById.get(d.driverId);
    if (!driver) continue;
    const loadingFeePerBag = driver.loadingFee > 0 ? driver.loadingFee : fallbackLoadingFeePerBag;
    if (loadingFeePerBag <= 0) continue;
    const amount = d.bags * loadingFeePerBag;
    expenses.push({
      description: `Loading fee — ${driver.name}`,
      amount,
      amountPaid: d.loadingFeePaid ? amount : 0,
      paid: d.loadingFeePaid,
      paidAt: d.loadingFeePaid ? new Date() : null,
      paidById: d.loadingFeePaid ? paidById : null,
    });
  }
  return expenses;
}

/**
 * Every truck delivery's fuel cost (own truck) or hired-truck price, plus
 * its loading/offloading fee (fixed ₦/bag rates set on Settings, applying
 * regardless of own vs hired truck), is logged as its own expense line —
 * same treatment as driver loading fees — so it shows up on the Expenses
 * page and can be marked paid/owing there, instead of only being visible as
 * a field on the delivery itself.
 */
function buildTruckCostExpenses(
  truckDeliveries: {
    customerId: string;
    bags: number;
    ownTruck: boolean;
    fuelCost: number;
    loadingFeeWaived: boolean;
    offloadingFeeWaived: boolean;
    hiredCostWaived: boolean;
    fuelPaid: boolean;
    hiredCostPaid: boolean;
    loadingFeePaid: boolean;
    offloadingFeePaid: boolean;
  }[],
  customerById: Map<string, { name: string }>,
  truckLoadingFeePerBag: number,
  truckOffloadingFeePerBag: number,
  truckHiredCostPerBag: number,
  paidById: string
) {
  const expenses: {
    description: string;
    amount: number;
    amountPaid: number;
    paid: boolean;
    paidAt: Date | null;
    paidById: string | null;
  }[] = [];
  const push = (description: string, amount: number, isPaid: boolean) => {
    expenses.push({
      description,
      amount,
      amountPaid: isPaid ? amount : 0,
      paid: isPaid,
      paidAt: isPaid ? new Date() : null,
      paidById: isPaid ? paidById : null,
    });
  };
  for (const t of truckDeliveries) {
    const customerName = customerById.get(t.customerId)?.name ?? "no customer";

    if (t.ownTruck) {
      if (t.fuelCost > 0) push(`Truck fuel — ${customerName}`, t.fuelCost, t.fuelPaid);
    } else if (t.bags > 0 && !t.hiredCostWaived && truckHiredCostPerBag > 0) {
      push(`Hired truck — ${customerName}`, t.bags * truckHiredCostPerBag, t.hiredCostPaid);
    }

    if (t.bags > 0 && !t.loadingFeeWaived && truckLoadingFeePerBag > 0) {
      push(`Loading fee — ${customerName}`, t.bags * truckLoadingFeePerBag, t.loadingFeePaid);
    }
    if (t.bags > 0 && !t.offloadingFeeWaived && truckOffloadingFeePerBag > 0) {
      push(`Offloading fee — ${customerName}`, t.bags * truckOffloadingFeePerBag, t.offloadingFeePaid);
    }
  }
  return expenses;
}

interface DesiredExpense {
  description: string;
  amount: number;
  /** The "paid" tick as it stands in the form when saved. */
  paid: boolean;
  rollsKg: number | null;
  packingBagsBundles: number | null;
  packingBagTypeId: string | null;
}

/**
 * Brings a record's expense lines in line with an edit without wiping them:
 * each wanted line reuses an existing line with the same description (in
 * order), so its payment history, who paid it, and when stay intact and a
 * paid fee can't come back as owing and get paid twice. Lines no longer
 * wanted are removed; new ones are created.
 *
 * Paid tick on a reused line: ticked → fully paid (keeps the original
 * paidAt/paidBy if it already was); unticked → back to unpaid if it had been
 * fully paid, otherwise any part-payment is kept.
 */
async function syncExpenseItems(
  tx: Prisma.TransactionClient,
  dailyRecordId: string,
  desired: DesiredExpense[],
  userId: string
) {
  const current = await tx.expenseItem.findMany({ where: { dailyRecordId }, orderBy: { id: "asc" } });
  const unused = [...current];
  const now = new Date();

  for (const want of desired) {
    const idx = unused.findIndex((c) => c.description === want.description);
    const details = {
      amount: want.amount,
      rollsKg: want.rollsKg,
      packingBagsBundles: want.packingBagsBundles,
      packingBagTypeId: want.packingBagTypeId,
    };
    if (idx === -1) {
      await tx.expenseItem.create({
        data: {
          dailyRecordId,
          description: want.description,
          ...details,
          amountPaid: want.paid ? want.amount : 0,
          paid: want.paid,
          paidAt: want.paid ? now : null,
          paidById: want.paid ? userId : null,
        },
      });
      continue;
    }
    const [old] = unused.splice(idx, 1);
    let payment: Prisma.ExpenseItemUncheckedUpdateInput;
    if (want.paid) {
      payment =
        old.paid && old.amountPaid >= want.amount
          ? {}
          : { amountPaid: want.amount, paid: true, paidAt: old.paidAt ?? now, paidById: old.paidById ?? userId };
    } else if (old.amountPaid >= want.amount || old.paid) {
      await tx.expensePayment.deleteMany({ where: { expenseItemId: old.id } });
      payment = { amountPaid: 0, paid: false, paidAt: null, paidById: null };
    } else {
      payment = { paid: false };
    }
    await tx.expenseItem.update({ where: { id: old.id }, data: { ...details, ...payment } });
  }

  if (unused.length > 0) {
    await tx.expenseItem.deleteMany({ where: { id: { in: unused.map((u) => u.id) } } });
  }
}

/**
 * Packers are entered as free text on the daily record form, same as before —
 * there's no separate "add packer" step. Matching an existing name (case-
 * insensitively) reuses that packer's id and history; an unrecognized name
 * creates a new Packer record on the spot. Pay is a single ₦/bag rate that
 * applies to every packer (set on Settings), not a per-packer rate.
 */
async function resolvePackers(
  names: string[],
  createdById: string
): Promise<Map<string, { id: string; name: string }>> {
  const trimmedNames = [...new Set(names.map((n) => n.trim()).filter(Boolean))];
  const result = new Map<string, { id: string; name: string }>();
  for (const name of trimmedNames) {
    const key = name.toLowerCase();
    let packer = await prisma.packer.findFirst({ where: { name: { equals: name, mode: "insensitive" } } });
    if (!packer) {
      packer = await prisma.packer.create({ data: { name, createdById } });
    }
    result.set(key, packer);
  }
  return result;
}

